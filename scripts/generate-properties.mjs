// Generates src/properties-data.lil from property-information: for the html and svg schemas, each
// normalized (lowercase) name maps to its React prop key, with a trailing "," when the value list is
// comma-separated. `find` falls back to upstream's data-*/unknown rules for names not listed.
import {writeFileSync, readFileSync} from 'node:fs'
import {createRequire} from 'node:module'
import {pathToFileURL} from 'node:url'
const require = createRequire('/home/azureuser/react-markdownlil/package.json')
const pi = await import(pathToFileURL(require.resolve('property-information')).href)
const version = JSON.parse(readFileSync('/home/azureuser/react-markdownlil/node_modules/property-information/package.json', 'utf8')).version
const table = schema => {
  const out = {}
  for (const normal of Object.keys(schema.normal).sort()) {
    const info = schema.property[schema.normal[normal]]
    const key = info.space ? (pi.hastToReact[info.property] || info.property) : info.attribute
    out[normal] = key + (info.commaSeparated ? ',' : '')
  }
  return out
}
const lit = obj => 'object {\n' + Object.entries(obj).map(([k, v]) => '  ' + (/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : JSON.stringify(k)) + ': ' + JSON.stringify(v)).join(',\n') + '\n}'
const html = table(pi.html), svg = table(pi.svg)
writeFileSync('src/properties-data.lil', `// property-information ${version}: normalized name -> React prop key (",": comma-separated), per schema.
// Generated by scripts/generate-properties.mjs.
export JsValue htmlKeys = ${lit(html)};

export JsValue svgKeys = ${lit(svg)};
`)
console.log('html', Object.keys(html).length, 'svg', Object.keys(svg).length)
